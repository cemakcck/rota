"use client";

import { useEffect, useState, type FormEvent } from "react";
import QRCode from "qrcode";
import { useTranslations } from "next-intl";
import { apiFetch } from "@/client/authClient";
import { errorMessage, readError } from "@/client/apiError";
import { Field } from "../Field";
import { btn, btnPrimary, btnSm, errorText, hint } from "../ui";

type Invite = { id: string; kind: "link" | "email"; email: string | null };
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function Qr({ url, label }: { url: string; label: string }) {
  const [svg, setSvg] = useState("");
  useEffect(() => {
    let live = true;
    QRCode.toString(url, { type: "svg", margin: 1, width: 176 }).then((out) => live && setSvg(out), () => undefined);
    return () => {
      live = false;
    };
  }, [url]);
  // The SVG is generated by the qrcode library from our own URL, not from user markup.
  return (
    <div role="img" aria-label={label} className="size-44 rounded-lg border border-line bg-white">
      <div data-testid="qr" dangerouslySetInnerHTML={{ __html: svg }} />
    </div>
  );
}

/** Owner-only: the join link (with QR and copy) and email invites. */
export function InvitePanel({ tripId, locale, onMembersChanged }: { tripId: string; locale: string; onMembersChanged?: () => void }) {
  const t = useTranslations("invites");
  const tc = useTranslations("common");
  const te = useTranslations("errors");
  const [invites, setInvites] = useState<Invite[]>([]);
  const [url, setUrl] = useState("");
  const [copied, setCopied] = useState<"" | "yes" | "no">("");
  const [email, setEmail] = useState("");
  const [emailError, setEmailError] = useState("");
  const [message, setMessage] = useState("");
  const [failure, setFailure] = useState("");

  const base = `/api/trips/${tripId}/invites`;
  const [version, setVersion] = useState(0);
  const reload = () => setVersion((v) => v + 1);
  useEffect(() => {
    let live = true;
    (async () => {
      try {
        const res = await apiFetch(base);
        if (res.ok && live) setInvites((await res.json()) as Invite[]);
      } catch {
        // Offline: the list stays as it was.
      }
    })();
    return () => {
      live = false;
    };
  }, [base, version]);

  const activeLink = invites.find((i) => i.kind === "link");
  const pending = invites.filter((i) => i.kind === "email");

  async function send(init: RequestInit, path = base): Promise<Response | null> {
    setFailure("");
    try {
      const res = await apiFetch(path, init);
      if (!res.ok) {
        setFailure(errorMessage(te, await readError(res)));
        return null;
      }
      return res;
    } catch {
      setFailure(te("offline"));
      return null;
    }
  }

  async function makeLink() {
    const res = await send({ method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ kind: "link" }) });
    if (!res) return;
    const { token } = (await res.json()) as { token: string };
    setUrl(`${window.location.origin}/${locale}/invite/${token}`);
    setCopied("");
    reload();
  }

  async function disableLink() {
    if (!activeLink || !(await send({ method: "DELETE" }, `${base}/${activeLink.id}`))) return;
    setUrl("");
    reload();
  }

  async function copy() {
    try {
      await navigator.clipboard.writeText(url);
      setCopied("yes");
    } catch {
      setCopied("no");
    }
  }

  async function inviteByEmail(e: FormEvent) {
    e.preventDefault();
    setMessage("");
    if (!EMAIL.test(email.trim())) return setEmailError(t("emailInvalid"));
    setEmailError("");
    const address = email.trim();
    const res = await send({ method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ kind: "email", email: address }) });
    if (!res) return;
    const { status } = (await res.json()) as { status: "added" | "already_member" | "pending" };
    setMessage(t(status === "already_member" ? "alreadyMember" : status, { email: address }));
    setEmail("");
    if (status === "added") onMembersChanged?.();
    reload();
  }

  async function cancel(id: string) {
    if (await send({ method: "DELETE" }, `${base}/${id}`)) reload();
  }

  return (
    <section aria-labelledby="invites-title" className="grid gap-6">
      <h3 id="invites-title" className="text-[15px] font-semibold">
        {t("title")}
      </h3>

      <div className="grid gap-3">
        <h4 className="font-medium">{t("linkTitle")}</h4>
        <p className={hint}>{t("linkHelp")}</p>
        {url ? (
          <div className="grid gap-3">
            <div className="flex gap-2">
              <div className="flex-1">
                <label htmlFor="join-link" className="sr-only">
                  {t("linkLabel")}
                </label>
                <input id="join-link" readOnly value={url} onFocus={(e) => e.target.select()} className="h-9 max-lg:h-11 w-full rounded-lg border border-ink-2 bg-surface px-3 font-mono text-[12.5px]" />
              </div>
              <button type="button" className={`${btn} ${btnSm}`} onClick={copy}>
                {t("copyLink")}
              </button>
            </div>
            <div aria-live="polite">
              {copied === "yes" && <p role="status" className="font-medium text-ok">{t("copiedLink")}</p>}
              {copied === "no" && <p role="status" className={errorText}>{t("copyFailed")}</p>}
            </div>
            <Qr url={url} label={t("qrLabel")} />
          </div>
        ) : (
          <p className="text-ink-2">{activeLink ? t("linkActive") : t("noLink")}</p>
        )}
        <div className="flex gap-2">
          <button type="button" className={`${activeLink ? btn : btnPrimary} ${btnSm}`} onClick={makeLink}>
            {activeLink ? t("regenerate") : t("create")}
          </button>
          {activeLink && (
            <button type="button" className={`${btn} ${btnSm}`} onClick={disableLink}>
              {t("disable")}
            </button>
          )}
        </div>
      </div>

      <form onSubmit={inviteByEmail} noValidate className="grid gap-3">
        <h4 className="font-medium">{t("emailTitle")}</h4>
        <Field id="invite-email" type="email" label={t("email")} error={emailError} value={email} onChange={(e) => setEmail(e.target.value)} autoComplete="off" />
        <div>
          <button type="submit" className={`${btnPrimary} ${btnSm}`}>
            {t("send")}
          </button>
        </div>
        <div aria-live="polite">{message && <p role="status" className="font-medium text-ok">{message}</p>}</div>
      </form>

      <div>
        <h4 id="pending-title" className="mb-2 font-medium">
          {t("pendingTitle")}
        </h4>
        {pending.length === 0 ? (
          <p className="text-ink-2">{t("none")}</p>
        ) : (
          <ul aria-labelledby="pending-title" className="grid gap-2">
            {pending.map((invite) => (
              <li key={invite.id} className="flex items-center justify-between gap-2 rounded-lg border border-line bg-surface p-2.5">
                <span className="min-w-0 truncate">{invite.email}</span>
                <button type="button" className={`${btn} ${btnSm}`} aria-label={t("cancelFor", { email: invite.email ?? "" })} onClick={() => cancel(invite.id)}>
                  {tc("cancel")}
                </button>
              </li>
            ))}
          </ul>
        )}
      </div>

      {failure && (
        <p role="alert" className={errorText}>
          {failure}
        </p>
      )}
    </section>
  );
}
